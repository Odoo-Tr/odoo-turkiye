def account_number(code):
    """Hesabın 3'lü kebir kodu; Tek Düzen Hesap Planı'na uymuyorsa None."""
    code = (code or "").strip()
    return code[:3] if len(code) >= 3 and code[:3].isdigit() else None


def line_number(prefix):
    """Ayrıntılı formdaki sıra numarası: hesabın kendi 2'li grubu içindeki yeri."""
    if "171" <= prefix <= "177":
        prefix = "170"
    group = [c for c in ACCOUNTS if c[:2] == prefix[:2] and not ("171" <= c <= "177")]
    return group.index(prefix) + 1 if prefix in group else None
